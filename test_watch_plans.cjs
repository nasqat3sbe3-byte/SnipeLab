'use strict';
const assert=require('node:assert/strict');
const {evaluate,personalTransitions}=require('./watch-plans.js');
const manual={id:'manual',type:'manual',checked:true};
const available={id:'a',type:'available',target:10000,createdAt:'2026-10-27T10:00:00Z'};
const stable={id:'s',type:'stability',target:3};
assert.equal(evaluate(manual,{}),true);
assert.equal(evaluate(available,{available:0}),true);
assert.equal(evaluate(available,{available:10000}),false);
assert.equal(evaluate(available,{available:null}),null);
assert.equal(evaluate(stable,{stability:2}),false);
assert.equal(evaluate(stable,{stability:3}),true);
assert.equal(evaluate({type:'retest'},{retest:'failed'}),false);
assert.equal(evaluate({type:'retest'},{}),null);
const plan={context:'2026-10-01',createdAt:'2026-10-27T10:00:00Z',rules:[available,manual]};
const event={seq:1,namespace:'journal-1',symbol:'TEST',market:'split',context:plan.context,at:'2026-10-27T10:20:00Z',changed:['available'],before:{available:25000},after:{available:5000}};
const met=personalTransitions(event,plan);assert.equal(met.length,1);assert.match(met[0].title,/تحقق شرطك/);
const failed=personalTransitions({...event,seq:2,before:{available:5000},after:{available:12000}},plan);assert.equal(failed.length,1);assert.match(failed[0].title,/اختل شرطك/);
assert.notEqual(failed[0].id,met[0].id);
assert.equal(personalTransitions({...event,at:'2026-10-27T09:00:00Z'},plan).length,0);
assert.equal(personalTransitions({...event,context:'2026-10-26'},plan).length,0);
assert.equal(personalTransitions({...event,before:{available:null}},plan).length,0);
assert.equal(personalTransitions(event,{...plan,rules:[{...available,createdAt:'2026-10-27T11:00:00Z'}]}).length,0);
console.log('Plan conditions, missing data, exact boundaries, fulfillment, reversal, context and replay tests passed.');
